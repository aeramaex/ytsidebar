// YouTube Transcript Extractor - DEBUGGING VERSION
// This version includes extensive logging to diagnose what's going wrong

class DebugTranscriptExtractor {
    constructor() {
        this.cache = new Map();
        this.lastRequestTime = 0;
        this.requestDelay = 1000;
        this.maxRetries = 3;
        this.debugMode = true;
        
        this.log('🚀 Debug Transcript Extractor initialized');
    }

    log(message, data = null) {
        const timestamp = new Date().toLocaleTimeString();
        console.log(`[${timestamp}] ${message}`, data || '');
        
        // Also try to show in UI if possible
        try {
            const debugElement = document.getElementById('debug-output');
            if (debugElement) {
                debugElement.textContent += `\n[${timestamp}] ${message}`;
                debugElement.scrollTop = debugElement.scrollHeight;
            }
        } catch (e) {
            // Ignore if no debug element
        }
    }

    error(message, error = null) {
        const timestamp = new Date().toLocaleTimeString();
        console.error(`[${timestamp}] ❌ ${message}`, error || '');
        
        try {
            const debugElement = document.getElementById('debug-output');
            if (debugElement) {
                debugElement.textContent += `\n[${timestamp}] ❌ ${message}`;
                if (error) debugElement.textContent += `\n   Error: ${error.message || error}`;
                debugElement.scrollTop = debugElement.scrollHeight;
            }
        } catch (e) {
            // Ignore if no debug element
        }
    }

    // Extract video ID with extensive logging
    extractVideoId(url = window.location.href) {
        this.log('🔍 Starting video ID extraction', url);
        
        if (!url) {
            this.error('No URL provided for video ID extraction');
            return null;
        }
        
        const patterns = [
            /(?:youtube\.com\/watch\?v=|youtu\.be\/|youtube\.com\/embed\/)([^&\n?#]+)/,
            /^([a-zA-Z0-9_-]{11})$/
        ];
        
        for (let i = 0; i < patterns.length; i++) {
            const pattern = patterns[i];
            this.log(`🔍 Trying pattern ${i + 1}: ${pattern}`);
            
            const match = url.match(pattern);
            if (match) {
                const videoId = match[1];
                this.log(`✅ Video ID found: ${videoId}`);
                return videoId;
            }
        }
        
        // Try URL params as fallback
        try {
            const urlParams = new URLSearchParams(window.location.search);
            const videoId = urlParams.get('v');
            if (videoId && videoId.length === 11) {
                this.log(`✅ Video ID found in URL params: ${videoId}`);
                return videoId;
            }
        } catch (e) {
            this.error('Failed to parse URL parameters', e);
        }
        
        this.error('❌ No video ID found in URL');
        return null;
    }

    // Rate limiting with logging
    async waitForRateLimit() {
        const now = Date.now();
        const timeSinceLastRequest = now - this.lastRequestTime;
        
        if (timeSinceLastRequest < this.requestDelay) {
            const waitTime = this.requestDelay - timeSinceLastRequest;
            this.log(`⏱️ Rate limiting: waiting ${waitTime}ms`);
            await new Promise(resolve => setTimeout(resolve, waitTime));
        }
        
        this.lastRequestTime = Date.now();
    }

    // Extract from current page with detailed logging
    extractTracksFromCurrentPage() {
        this.log('🔍 Attempting to extract tracks from current page');
        
        try {
            // Method 1: Check window.ytInitialPlayerResponse
            this.log('📋 Checking window.ytInitialPlayerResponse');
            if (window.ytInitialPlayerResponse) {
                this.log('✅ Found window.ytInitialPlayerResponse');
                
                if (window.ytInitialPlayerResponse.captions) {
                    this.log('✅ Found captions in ytInitialPlayerResponse');
                    
                    const captions = window.ytInitialPlayerResponse.captions?.playerCaptionsTracklistRenderer?.captionTracks;
                    if (captions && Array.isArray(captions) && captions.length > 0) {
                        this.log(`✅ Found ${captions.length} caption tracks in window object`);
                        return captions.map(track => ({
                            url: track.baseUrl,
                            languageCode: track.languageCode,
                            name: track.name?.simpleText || track.languageCode,
                            isAutoGenerated: track.kind === 'asr'
                        }));
                    } else {
                        this.log('❌ No caption tracks in ytInitialPlayerResponse');
                    }
                } else {
                    this.log('❌ No captions property in ytInitialPlayerResponse');
                }
            } else {
                this.log('❌ window.ytInitialPlayerResponse not found');
            }
            
            // Method 2: Extract from script tags
            this.log('📋 Searching script tags for player data');
            const scripts = document.querySelectorAll('script');
            this.log(`🔍 Found ${scripts.length} script tags to check`);
            
            for (let i = 0; i < scripts.length; i++) {
                const script = scripts[i];
                const content = script.textContent || '';
                
                if (content.includes('ytInitialPlayerResponse') && content.includes('captionTracks')) {
                    this.log(`✅ Found promising script tag ${i + 1}`);
                    
                    try {
                        const patterns = [
                            /var ytInitialPlayerResponse = ({.+?});/,
                            /ytInitialPlayerResponse":\s*({.+?})(?:,|}|;)/,
                            /"ytInitialPlayerResponse":({.+?})(?:,|})/
                        ];
                        
                        for (let j = 0; j < patterns.length; j++) {
                            const pattern = patterns[j];
                            this.log(`🔍 Trying script pattern ${j + 1}`);
                            
                            const match = content.match(pattern);
                            if (match) {
                                this.log(`✅ Pattern ${j + 1} matched, parsing JSON`);
                                
                                const playerResponse = JSON.parse(match[1]);
                                const captions = playerResponse?.captions?.playerCaptionsTracklistRenderer?.captionTracks;
                                
                                if (captions && Array.isArray(captions) && captions.length > 0) {
                                    this.log(`✅ Found ${captions.length} caption tracks in script tag`);
                                    return captions.map(track => ({
                                        url: track.baseUrl,
                                        languageCode: track.languageCode,
                                        name: track.name?.simpleText || track.languageCode,
                                        isAutoGenerated: track.kind === 'asr'
                                    }));
                                }
                            }
                        }
                    } catch (e) {
                        this.error(`Failed to parse script tag ${i + 1}`, e);
                    }
                }
            }
            
            this.log('❌ No caption tracks found in current page');
            return [];
            
        } catch (error) {
            this.error('Error extracting tracks from current page', error);
            return [];
        }
    }

    // Fetch with detailed error handling
    async fetchWithTimeout(url, options = {}, timeout = 10000) {
        this.log(`🌐 Fetching: ${url.substring(0, 100)}...`);
        
        const controller = new AbortController();
        const timeoutId = setTimeout(() => {
            controller.abort();
            this.error(`Request timeout after ${timeout}ms`);
        }, timeout);

        try {
            const response = await fetch(url, {
                ...options,
                signal: controller.signal
            });
            
            clearTimeout(timeoutId);
            
            this.log(`📨 Response: ${response.status} ${response.statusText}`);
            
            if (!response.ok) {
                throw new Error(`HTTP ${response.status}: ${response.statusText}`);
            }
            
            return response;
            
        } catch (error) {
            clearTimeout(timeoutId);
            this.error('Fetch failed', error);
            throw error;
        }
    }

    // Parse transcript XML with extensive logging
    parseTranscriptXML(xmlText) {
        this.log(`📝 Parsing XML transcript (${xmlText.length} characters)`);
        
        try {
            const transcript = [];
            
            if (!xmlText || xmlText.trim().length === 0) {
                this.error('Empty XML text provided');
                return [];
            }
            
            // Log first 200 characters of XML for debugging
            this.log('📄 XML preview:', xmlText.substring(0, 200) + '...');
            
            const textMatches = xmlText.matchAll(/<text[^>]*>(.*?)<\/text>/gs);
            let matchCount = 0;
            
            for (const match of textMatches) {
                matchCount++;
                const textTag = match[0];
                const content = match[1];
                
                // Extract attributes
                const start = parseFloat(this.extractAttribute(textTag, 'start') || '0');
                const dur = parseFloat(this.extractAttribute(textTag, 'dur') || '0');
                
                // Clean text
                const text = this.cleanTranscriptText(content);
                
                if (text && text.trim()) {
                    transcript.push({
                        start: start,
                        duration: dur,
                        text: text.trim()
                    });
                }
                
                // Log progress every 50 matches
                if (matchCount % 50 === 0) {
                    this.log(`📝 Processed ${matchCount} text elements`);
                }
            }
            
            this.log(`✅ Parsed ${transcript.length} transcript segments from ${matchCount} text elements`);
            return transcript;
            
        } catch (error) {
            this.error('Error parsing transcript XML', error);
            return [];
        }
    }

    // Extract attribute with logging
    extractAttribute(tag, attributeName) {
        const regex = new RegExp(`${attributeName}=["']([^"']*)["']`, 'i');
        const match = tag.match(regex);
        return match ? match[1] : null;
    }

    // Clean text
    cleanTranscriptText(text) {
        return text
            .replace(/&amp;/g, '&')
            .replace(/&lt;/g, '<')
            .replace(/&gt;/g, '>')
            .replace(/&quot;/g, '"')
            .replace(/&#39;/g, "'")
            .replace(/&nbsp;/g, ' ')
            .replace(/<[^>]*>/g, '')
            .replace(/\s+/g, ' ')
            .trim();
    }

    // Main extraction with comprehensive error handling
    async getTranscript(videoId = null, languageCode = 'en') {
        this.log('🎬 Starting transcript extraction');
        
        try {
            // Step 1: Get video ID
            if (!videoId) {
                this.log('🔍 No video ID provided, attempting auto-detection');
                videoId = this.extractVideoId();
                if (!videoId) {
                    throw new Error('Could not determine video ID from current page');
                }
            }
            
            this.log(`🎯 Target video: ${videoId}, language: ${languageCode}`);
            
            // Step 2: Check cache
            const cacheKey = `${videoId}_${languageCode}`;
            if (this.cache.has(cacheKey)) {
                this.log('💾 Returning cached transcript');
                return this.cache.get(cacheKey);
            }
            
            // Step 3: Try current page extraction first
            this.log('📋 Attempting current page extraction');
            let tracks = this.extractTracksFromCurrentPage();
            
            if (!tracks || tracks.length === 0) {
                this.log('⚠️ No tracks from current page, trying API fallback');
                tracks = await this.getCaptionTracksFromAPI(videoId);
            }
            
            if (!tracks || tracks.length === 0) {
                throw new Error('No caption tracks available for this video');
            }
            
            this.log(`📋 Available tracks: ${tracks.map(t => `${t.languageCode} (${t.name})`).join(', ')}`);
            
            // Step 4: Select best track
            let selectedTrack = tracks.find(track => 
                track.languageCode === languageCode && !track.isAutoGenerated
            ) || tracks.find(track => 
                track.languageCode === languageCode
            ) || tracks.find(track => 
                track.languageCode.startsWith(languageCode.split('-')[0])
            ) || tracks[0];
            
            if (!selectedTrack) {
                throw new Error('No suitable caption track found');
            }
            
            this.log(`🎯 Selected track: ${selectedTrack.languageCode} (${selectedTrack.name})`);
            
            // Step 5: Download transcript
            await this.waitForRateLimit();
            
            const response = await this.fetchWithTimeout(selectedTrack.url, {
                headers: {
                    'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36',
                    'Accept': 'application/xml,text/xml,*/*',
                    'Accept-Language': 'en-US,en;q=0.9'
                }
            });
            
            const xmlText = await response.text();
            this.log(`📥 Downloaded transcript data (${xmlText.length} characters)`);
            
            // Step 6: Parse transcript
            const transcript = this.parseTranscriptXML(xmlText);
            
            if (!transcript || transcript.length === 0) {
                throw new Error('No transcript segments found in downloaded data');
            }
            
            // Step 7: Cache and return
            this.cache.set(cacheKey, transcript);
            this.log(`✅ Successfully extracted ${transcript.length} transcript segments`);
            
            return transcript;
            
        } catch (error) {
            this.error('Transcript extraction failed', error);
            throw error;
        }
    }

    // API fallback method
    async getCaptionTracksFromAPI(videoId) {
        this.log(`🌐 Fetching caption tracks from API for video: ${videoId}`);
        
        try {
            await this.waitForRateLimit();
            
            const response = await this.fetchWithTimeout(`https://www.youtube.com/watch?v=${videoId}`, {
                headers: {
                    'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36',
                    'Accept': 'text/html,application/xhtml+xml,application/xml;q=0.9,*/*;q=0.8'
                }
            });
            
            const html = await response.text();
            this.log(`📄 Downloaded page HTML (${html.length} characters)`);
            
            return this.extractCaptionTracksFromHTML(html);
            
        } catch (error) {
            this.error('API fallback failed', error);
            return [];
        }
    }

    // Extract from HTML
    extractCaptionTracksFromHTML(html) {
        this.log('🔍 Extracting caption tracks from HTML');
        
        try {
            const playerResponseMatch = html.match(/var ytInitialPlayerResponse = ({.+?});/);
            if (!playerResponseMatch) {
                this.log('❌ No player response found in HTML');
                return [];
            }
            
            const playerResponse = JSON.parse(playerResponseMatch[1]);
            const captions = playerResponse?.captions?.playerCaptionsTracklistRenderer?.captionTracks;
            
            if (!captions || !Array.isArray(captions)) {
                this.log('❌ No captions found in player response');
                return [];
            }
            
            this.log(`✅ Found ${captions.length} caption tracks in HTML`);
            return captions.map(track => ({
                url: track.baseUrl,
                languageCode: track.languageCode,
                name: track.name?.simpleText || track.languageCode,
                isAutoGenerated: track.kind === 'asr'
            }));
            
        } catch (error) {
            this.error('Error parsing HTML for captions', error);
            return [];
        }
    }

    // Quick diagnostic function
    async diagnose() {
        this.log('🔬 Running diagnostic...');
        
        try {
            const videoId = this.extractVideoId();
            this.log(`Video ID: ${videoId || 'NOT FOUND'}`);
            
            const pageHasYtData = !!window.ytInitialPlayerResponse;
            this.log(`Page has ytInitialPlayerResponse: ${pageHasYtData}`);
            
            if (pageHasYtData && window.ytInitialPlayerResponse.captions) {
                const captionCount = window.ytInitialPlayerResponse.captions?.playerCaptionsTracklistRenderer?.captionTracks?.length || 0;
                this.log(`Captions available: ${captionCount}`);
            }
            
            const url = window.location.href;
            this.log(`Current URL: ${url}`);
            
            return {
                videoId,
                pageHasYtData,
                url,
                timestamp: new Date().toISOString()
            };
            
        } catch (error) {
            this.error('Diagnostic failed', error);
            return null;
        }
    }
}

// Create global instance
window.debugExtractor = new DebugTranscriptExtractor();

// Auto-run diagnostic
window.debugExtractor.diagnose();

