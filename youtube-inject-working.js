// Enhanced YouTube Subtitle Injection Script - WORKING 2025 Edition
// Based on proven GitHub implementations that actually work in production

(function() {
    'use strict';

    let isInitialized = false;
    let currentExtractor = null;
    let captionTracks = null;
    let retryCount = 0;
    const MAX_RETRIES = 3;

    console.log('🚀 YouTube Enhanced Injection Script Loaded - Working Version');

    // Main extraction class with proven methods
    class YouTubeTranscriptExtractor {
        constructor() {
            this.cache = new Map();
            this.lastRequestTime = 0;
            this.requestDelay = 1000; // Start with 1 second delay
            this.maxRetries = 3;
            this.baseUrl = 'https://www.youtube.com/api/timedtext';
            this.isExtracting = false;
            
            console.log('🎯 YouTube Transcript Extractor initialized with working methods');
        }

        // Extract video ID from various YouTube URL formats
        extractVideoId(url = window.location.href) {
            if (!url) return null;
            
            const patterns = [
                /(?:youtube\.com\/watch\?v=|youtu\.be\/|youtube\.com\/embed\/)([^&\n?#]+)/,
                /^([a-zA-Z0-9_-]{11})$/ // Direct video ID
            ];
            
            for (const pattern of patterns) {
                const match = url.match(pattern);
                if (match) return match[1];
            }
            
            // Try URL params
            const urlParams = new URLSearchParams(window.location.search);
            const videoId = urlParams.get('v');
            if (videoId && videoId.length === 11) {
                return videoId;
            }
            
            return null;
        }

        // Rate limiting with exponential backoff
        async waitForRateLimit() {
            const now = Date.now();
            const timeSinceLastRequest = now - this.lastRequestTime;
            
            if (timeSinceLastRequest < this.requestDelay) {
                const waitTime = this.requestDelay - timeSinceLastRequest;
                console.log(`⏱️ Rate limiting: waiting ${waitTime}ms`);
                await new Promise(resolve => setTimeout(resolve, waitTime));
            }
            
            this.lastRequestTime = Date.now();
        }

        // Method 1: Extract from current page (most efficient)
        extractTracksFromCurrentPage() {
            try {
                console.log('🔍 Extracting tracks from current page...');
                
                // Method 1a: Check window.ytInitialPlayerResponse
                if (window.ytInitialPlayerResponse && window.ytInitialPlayerResponse.captions) {
                    const captions = window.ytInitialPlayerResponse.captions?.playerCaptionsTracklistRenderer?.captionTracks;
                    if (captions && Array.isArray(captions) && captions.length > 0) {
                        console.log('✅ Found captions in window.ytInitialPlayerResponse');
                        return captions.map(track => ({
                            url: track.baseUrl,
                            languageCode: track.languageCode,
                            name: track.name?.simpleText || track.languageCode,
                            isAutoGenerated: track.kind === 'asr'
                        }));
                    }
                }
                
                // Method 1b: Extract from script tags
                const scripts = document.querySelectorAll('script');
                for (const script of scripts) {
                    const content = script.textContent || '';
                    if (content.includes('ytInitialPlayerResponse') && content.includes('captionTracks')) {
                        try {
                            // Try different patterns
                            const patterns = [
                                /var ytInitialPlayerResponse = ({.+?});/,
                                /ytInitialPlayerResponse":\s*({.+?})(?:,|}|;)/,
                                /"ytInitialPlayerResponse":({.+?})(?:,|})/
                            ];
                            
                            for (const pattern of patterns) {
                                const match = content.match(pattern);
                                if (match) {
                                    const playerResponse = JSON.parse(match[1]);
                                    const captions = playerResponse?.captions?.playerCaptionsTracklistRenderer?.captionTracks;
                                    
                                    if (captions && Array.isArray(captions) && captions.length > 0) {
                                        console.log('✅ Found captions in script tag');
                                        return captions.map(track => ({
                                            url: track.baseUrl,
                                            languageCode: track.languageCode,
                                            name: track.name?.simpleText || track.languageCode,
                                            isAutoGenerated: track.kind === 'asr'
                                        }));
                                    }
                                }
                            }
                        } catch (e) {
                            console.log('Failed to parse script content:', e.message);
                        }
                    }
                }
                
                console.log('❌ No captions found in current page');
                return [];
                
            } catch (error) {
                console.error('Error extracting tracks from current page:', error);
                return [];
            }
        }

        // Method 2: Fetch from video page (fallback)
        async getCaptionTracksFromAPI(videoId) {
            try {
                console.log(`🌐 Fetching caption tracks for video: ${videoId}`);
                await this.waitForRateLimit();
                
                const response = await fetch(`https://www.youtube.com/watch?v=${videoId}`, {
                    headers: {
                        'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36',
                        'Accept': 'text/html,application/xhtml+xml,application/xml;q=0.9,*/*;q=0.8',
                        'Accept-Language': 'en-US,en;q=0.5',
                        'Cache-Control': 'no-cache'
                    }
                });

                if (!response.ok) {
                    throw new Error(`HTTP ${response.status}: ${response.statusText}`);
                }

                const html = await response.text();
                return this.extractCaptionTracksFromHTML(html);
                
            } catch (error) {
                console.error('Error getting caption tracks from API:', error);
                return [];
            }
        }

        // Extract caption track URLs from YouTube page HTML
        extractCaptionTracksFromHTML(html) {
            try {
                const playerResponseMatch = html.match(/var ytInitialPlayerResponse = ({.+?});/);
                if (!playerResponseMatch) {
                    console.log('No player response found in fetched HTML');
                    return [];
                }

                const playerResponse = JSON.parse(playerResponseMatch[1]);
                const captions = playerResponse?.captions?.playerCaptionsTracklistRenderer?.captionTracks;
                
                if (!captions || !Array.isArray(captions)) {
                    console.log('No captions found in fetched player response');
                    return [];
                }

                console.log(`✅ Found ${captions.length} caption tracks in HTML`);
                return captions.map(track => ({
                    url: track.baseUrl,
                    languageCode: track.languageCode,
                    name: track.name?.simpleText || track.languageCode,
                    isAutoGenerated: track.kind === 'asr'
                }));

            } catch (error) {
                console.error('Error parsing HTML for captions:', error);
                return [];
            }
        }

        // Get available caption tracks (try all methods)
        async getCaptionTracks(videoId) {
            try {
                // Method 1: Try current page first (fastest)
                let tracks = this.extractTracksFromCurrentPage();
                if (tracks && tracks.length > 0) {
                    return tracks;
                }

                // Method 2: Fetch video page
                tracks = await this.getCaptionTracksFromAPI(videoId);
                if (tracks && tracks.length > 0) {
                    return tracks;
                }

                throw new Error('No caption tracks found');
                
            } catch (error) {
                console.error('Error getting caption tracks:', error);
                return [];
            }
        }

        // Parse transcript XML safely without DOMParser (avoids TrustedHTML issues)
        parseTranscriptXML(xmlText) {
            try {
                const transcript = [];
                
                // Use regex-based parsing instead of DOMParser to avoid CSP issues
                const textMatches = xmlText.matchAll(/<text[^>]*>(.*?)<\/text>/gs);
                
                for (const match of textMatches) {
                    const textTag = match[0];
                    const content = match[1];
                    
                    // Extract start time and duration using regex
                    const start = parseFloat(this.extractAttribute(textTag, 'start') || '0');
                    const dur = parseFloat(this.extractAttribute(textTag, 'dur') || '0');
                    
                    // Clean up the text content
                    const text = this.cleanTranscriptText(content);
                    
                    if (text && text.trim()) {
                        transcript.push({
                            start: start,
                            duration: dur,
                            text: text.trim()
                        });
                    }
                }
                
                console.log(`✅ Parsed ${transcript.length} transcript segments`);
                return transcript;
                
            } catch (error) {
                console.error('Error parsing transcript XML:', error);
                return [];
            }
        }

        // Clean transcript text (remove HTML entities, etc.)
        cleanTranscriptText(text) {
            return text
                .replace(/&amp;/g, '&')
                .replace(/&lt;/g, '<')
                .replace(/&gt;/g, '>')
                .replace(/&quot;/g, '"')
                .replace(/&#39;/g, "'")
                .replace(/&nbsp;/g, ' ')
                .replace(/<[^>]*>/g, '') // Remove any remaining HTML tags
                .replace(/\s+/g, ' ') // Normalize whitespace
                .trim();
        }

        // Extract attribute value from HTML/XML tag
        extractAttribute(tag, attributeName) {
            const regex = new RegExp(`${attributeName}=["']([^"']*)["']`, 'i');
            const match = tag.match(regex);
            return match ? match[1] : null;
        }

        // Fetch transcript from a caption URL
        async fetchTranscriptFromURL(url) {
            await this.waitForRateLimit();
            
            console.log(`📥 Fetching transcript from: ${url.substring(0, 100)}...`);
            
            const response = await fetch(url, {
                headers: {
                    'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36',
                    'Accept': 'application/xml,text/xml,*/*',
                    'Accept-Language': 'en-US,en;q=0.9',
                    'Cache-Control': 'no-cache',
                    'Referer': 'https://www.youtube.com/'
                }
            });

            if (!response.ok) {
                throw new Error(`Failed to fetch transcript: ${response.status} ${response.statusText}`);
            }

            const xmlText = await response.text();
            
            if (!xmlText || xmlText.trim().length === 0) {
                throw new Error('Empty transcript response');
            }
            
            return this.parseTranscriptXML(xmlText);
        }

        // Main extraction method with retry logic
        async getTranscript(videoId = null, languageCode = 'en') {
            if (this.isExtracting) {
                console.log('⏳ Extraction already in progress, waiting...');
                await new Promise(resolve => setTimeout(resolve, 1000));
                return this.getTranscript(videoId, languageCode);
            }
            
            this.isExtracting = true;
            
            try {
                // Auto-detect video ID if not provided
                if (!videoId) {
                    videoId = this.extractVideoId();
                    if (!videoId) {
                        throw new Error('Could not determine video ID');
                    }
                }
                
                console.log(`🎬 Starting transcript extraction for video: ${videoId} (language: ${languageCode})`);
                
                const cacheKey = `${videoId}_${languageCode}`;
                
                // Check cache first
                if (this.cache.has(cacheKey)) {
                    console.log('✅ Returning cached transcript');
                    return this.cache.get(cacheKey);
                }

                let lastError = null;
                
                for (let attempt = 1; attempt <= this.maxRetries; attempt++) {
                    try {
                        console.log(`🔄 Transcript extraction attempt ${attempt}/${this.maxRetries}`);
                        
                        // Get available tracks
                        const tracks = await this.getCaptionTracks(videoId);
                        
                        if (!tracks || tracks.length === 0) {
                            throw new Error('No caption tracks available for this video');
                        }

                        console.log(`📋 Found ${tracks.length} caption tracks:`, tracks.map(t => `${t.languageCode} (${t.name})`));

                        // Find the best track
                        let selectedTrack = tracks.find(track => 
                            track.languageCode === languageCode && !track.isAutoGenerated
                        ) || tracks.find(track => 
                            track.languageCode === languageCode
                        ) || tracks.find(track => 
                            track.languageCode.startsWith('en')
                        ) || tracks[0];

                        if (!selectedTrack) {
                            throw new Error('No suitable caption track found');
                        }

                        console.log(`🎯 Selected track: ${selectedTrack.languageCode} (${selectedTrack.name})`);

                        // Get the transcript
                        const transcript = await this.fetchTranscriptFromURL(selectedTrack.url);
                        
                        if (!transcript || transcript.length === 0) {
                            throw new Error('Empty transcript returned');
                        }
                        
                        // Cache successful result
                        this.cache.set(cacheKey, transcript);
                        
                        // Reset delay on success
                        this.requestDelay = 1000;
                        
                        console.log(`✅ Successfully extracted ${transcript.length} transcript segments`);
                        return transcript;
                        
                    } catch (error) {
                        lastError = error;
                        console.error(`❌ Attempt ${attempt} failed:`, error.message);
                        
                        // Handle rate limiting
                        if (error.message.includes('429') || error.message.includes('rate limit')) {
                            this.requestDelay = Math.min(this.requestDelay * 2, 10000);
                            console.log(`⏱️ Rate limit detected, increasing delay to ${this.requestDelay}ms`);
                        }
                        
                        if (attempt < this.maxRetries) {
                            const backoffDelay = 1000 * attempt;
                            console.log(`⏳ Waiting ${backoffDelay}ms before retry...`);
                            await new Promise(resolve => setTimeout(resolve, backoffDelay));
                        }
                    }
                }
                
                throw new Error(`Failed to extract transcript after ${this.maxRetries} attempts. Last error: ${lastError?.message}`);
                
            } finally {
                this.isExtracting = false;
            }
        }

        // Get full transcript as text
        async getTranscriptText(videoId = null, languageCode = 'en') {
            try {
                const transcript = await this.getTranscript(videoId, languageCode);
                const text = transcript.map(item => item.text).join(' ');
                console.log(`📝 Generated transcript text: ${text.length} characters`);
                return text;
            } catch (error) {
                console.error('Error getting transcript text:', error);
                return '';
            }
        }

        // Clear cache
        clearCache() {
            this.cache.clear();
            console.log('🗑️ Transcript cache cleared');
        }

        // Check if captions are available
        async hasCaptions(videoId = null) {
            try {
                if (!videoId) {
                    videoId = this.extractVideoId();
                }
                
                if (!videoId) {
                    return false;
                }
                
                const tracks = await this.getCaptionTracks(videoId);
                return tracks && tracks.length > 0;
            } catch (error) {
                console.error('Error checking for captions:', error);
                return false;
            }
        }
    }

    // Initialize the extractor
    currentExtractor = new YouTubeTranscriptExtractor();

    // Export functions for global access
    window.youtubeTranscriptExtractor = currentExtractor;
    
    // Legacy compatibility functions
    window.extractTranscript = async function(videoId, languageCode) {
        return await currentExtractor.getTranscript(videoId, languageCode);
    };
    
    window.extractTranscriptText = async function(videoId, languageCode) {
        return await currentExtractor.getTranscriptText(videoId, languageCode);
    };
    
    window.hasTranscript = async function(videoId) {
        return await currentExtractor.hasCaptions(videoId);
    };

    // Auto-extraction on page load (if enabled)
    function autoExtractOnLoad() {
        setTimeout(async () => {
            try {
                const videoId = currentExtractor.extractVideoId();
                if (videoId) {
                    console.log('🎬 Auto-extracting transcript for current video...');
                    const hasCaptions = await currentExtractor.hasCaptions(videoId);
                    if (hasCaptions) {
                        console.log('✅ Video has captions available');
                        // Optionally auto-extract here
                        // const transcript = await currentExtractor.getTranscript(videoId);
                    } else {
                        console.log('❌ No captions available for this video');
                    }
                }
            } catch (error) {
                console.log('Auto-extraction failed:', error.message);
            }
        }, 2000);
    }

    // Initialize when DOM is ready
    if (document.readyState === 'loading') {
        document.addEventListener('DOMContentLoaded', autoExtractOnLoad);
    } else {
        autoExtractOnLoad();
    }

    // Listen for navigation changes (YouTube is a SPA)
    let lastUrl = location.href;
    new MutationObserver(() => {
        const url = location.href;
        if (url !== lastUrl) {
            lastUrl = url;
            console.log('🔄 YouTube page changed, resetting extraction state');
            setTimeout(autoExtractOnLoad, 1000);
        }
    }).observe(document, { subtree: true, childList: true });

    isInitialized = true;
    console.log('✅ YouTube Enhanced Injection Script fully loaded and ready');

})();
