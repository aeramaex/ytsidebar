// Advanced YouTube Subtitle Testing & Debugging Module
// This script provides real-time testing and debugging capabilities

class YouTubeSubtitleTester {
    constructor() {
        this.testResults = [];
        this.isRunning = false;
        this.debugMode = true;
    }

    // Real-time subtitle extraction test
    async runLiveTest(videoId = null) {
        if (this.isRunning) {
            console.log('🔄 Test already running...');
            return;
        }

        this.isRunning = true;
        console.log('🧪 Starting live subtitle extraction test...');

        try {
            // Get current video ID if not provided
            if (!videoId) {
                videoId = this.getCurrentVideoId();
            }

            if (!videoId) {
                throw new Error('No video ID found. Please navigate to a YouTube video.');
            }

            console.log(`🎯 Testing video: ${videoId}`);

            // Test all available methods
            const methods = [
                { name: 'Enhanced Page Extraction', fn: () => this.testPageExtraction(videoId) },
                { name: 'Direct API Call', fn: () => this.testDirectAPI(videoId) },
                { name: 'Multiple Format Test', fn: () => this.testMultipleFormats(videoId) },
                { name: 'Auto-Generated Test', fn: () => this.testAutoGenerated(videoId) }
            ];

            const results = [];

            for (const method of methods) {
                console.log(`🔍 Testing: ${method.name}`);
                const startTime = performance.now();
                
                try {
                    const result = await method.fn();
                    const duration = performance.now() - startTime;
                    
                    results.push({
                        method: method.name,
                        success: true,
                        subtitleCount: result?.length || 0,
                        duration: Math.round(duration),
                        data: result
                    });
                    
                    console.log(`✅ ${method.name}: ${result?.length || 0} subtitles in ${Math.round(duration)}ms`);
                } catch (error) {
                    const duration = performance.now() - startTime;
                    
                    results.push({
                        method: method.name,
                        success: false,
                        error: error.message,
                        duration: Math.round(duration)
                    });
                    
                    console.log(`❌ ${method.name}: ${error.message} (${Math.round(duration)}ms)`);
                }
            }

            // Display comprehensive results
            this.displayTestResults(results, videoId);
            return results;

        } catch (error) {
            console.error('🚨 Live test failed:', error);
        } finally {
            this.isRunning = false;
        }
    }

    getCurrentVideoId() {
        const urlParams = new URLSearchParams(window.location.search);
        let videoId = urlParams.get('v');
        
        if (!videoId) {
            const shortsMatch = window.location.pathname.match(/\/shorts\/([A-Za-z0-9_-]+)/);
            if (shortsMatch) {
                videoId = shortsMatch[1];
            }
        }
        
        return videoId;
    }

    async testPageExtraction(videoId) {
        // Test the enhanced page extraction method
        const extractor = new YouTubeTranscript();
        return await extractor.extractFromCurrentPageEnhanced(videoId);
    }

    async testDirectAPI(videoId) {
        // Test direct API call
        const response = await fetch(`https://www.youtube.com/api/timedtext?lang=en&v=${videoId}&fmt=json3`);
        if (!response.ok) {
            throw new Error(`HTTP ${response.status}`);
        }
        
        const data = await response.json();
        if (!data.events) {
            throw new Error('No events in response');
        }
        
        return this.parseJSON3Data(data);
    }

    async testMultipleFormats(videoId) {
        const formats = ['json3', 'vtt', 'ttml', 'srv3'];
        const languages = ['en', 'en-US'];
        
        for (const lang of languages) {
            for (const fmt of formats) {
                try {
                    const url = `https://www.youtube.com/api/timedtext?lang=${lang}&v=${videoId}&fmt=${fmt}`;
                    const response = await fetch(url);
                    
                    if (response.ok) {
                        const data = fmt === 'json3' ? await response.json() : await response.text();
                        
                        if (fmt === 'json3' && data.events) {
                            return this.parseJSON3Data(data);
                        } else if (data && data.trim()) {
                            return this.parseOtherFormats(data, fmt);
                        }
                    }
                } catch (error) {
                    continue;
                }
            }
        }
        
        throw new Error('All format tests failed');
    }

    async testAutoGenerated(videoId) {
        const autoUrl = `https://www.youtube.com/api/timedtext?v=${videoId}&asr_langs=en&caps=asr&fmt=json3`;
        const response = await fetch(autoUrl);
        
        if (!response.ok) {
            throw new Error(`Auto-generated test failed: HTTP ${response.status}`);
        }
        
        const data = await response.json();
        if (!data.events) {
            throw new Error('No auto-generated events found');
        }
        
        return this.parseJSON3Data(data);
    }

    parseJSON3Data(data) {
        const subtitles = [];
        for (const event of data.events || []) {
            if (event.segs) {
                const text = event.segs.map(seg => seg.utf8 || '').join('').trim();
                if (text) {
                    subtitles.push({
                        timestamp: (event.tStartMs || 0) / 1000,
                        text: text,
                        offset: event.tStartMs || 0
                    });
                }
            }
        }
        return subtitles;
    }

    parseOtherFormats(data, format) {
        // Simple parser for other formats (can be enhanced)
        const lines = data.split('\n').filter(line => line.trim());
        return lines.map((line, index) => ({
            timestamp: index * 5, // Rough estimate
            text: line.trim(),
            offset: index * 5000
        }));
    }

    displayTestResults(results, videoId) {
        console.log('\n📊 SUBTITLE EXTRACTION TEST RESULTS');
        console.log('=====================================');
        console.log(`🎥 Video ID: ${videoId}`);
        console.log(`⏰ Test Time: ${new Date().toLocaleTimeString()}`);
        console.log('');

        const successful = results.filter(r => r.success);
        const failed = results.filter(r => !r.success);

        console.log(`✅ Successful Methods: ${successful.length}/${results.length}`);
        console.log(`❌ Failed Methods: ${failed.length}/${results.length}`);
        console.log('');

        // Display successful methods
        if (successful.length > 0) {
            console.log('🎯 SUCCESSFUL EXTRACTIONS:');
            successful.forEach(result => {
                console.log(`  ✅ ${result.method}`);
                console.log(`     Subtitles: ${result.subtitleCount}`);
                console.log(`     Duration: ${result.duration}ms`);
                if (result.data && result.data.length > 0) {
                    console.log(`     Sample: "${result.data[0].text.substring(0, 50)}..."`);
                }
                console.log('');
            });
        }

        // Display failed methods
        if (failed.length > 0) {
            console.log('❌ FAILED EXTRACTIONS:');
            failed.forEach(result => {
                console.log(`  ❌ ${result.method}`);
                console.log(`     Error: ${result.error}`);
                console.log(`     Duration: ${result.duration}ms`);
                console.log('');
            });
        }

        // Recommendations
        console.log('💡 RECOMMENDATIONS:');
        if (successful.length === 0) {
            console.log('  🚨 No extraction methods worked. This video may not have captions.');
            console.log('  🔍 Try a different video with known captions.');
        } else {
            const fastest = successful.reduce((prev, current) => 
                prev.duration < current.duration ? prev : current
            );
            console.log(`  ⚡ Fastest method: ${fastest.method} (${fastest.duration}ms)`);
            
            const mostSubtitles = successful.reduce((prev, current) => 
                prev.subtitleCount > current.subtitleCount ? prev : current
            );
            console.log(`  📝 Most complete: ${mostSubtitles.method} (${mostSubtitles.subtitleCount} subtitles)`);
        }
        
        console.log('=====================================\n');

        // Store results for later analysis
        this.testResults.push({
            videoId,
            timestamp: Date.now(),
            results
        });
    }

    // Get historical test data
    getTestHistory() {
        return this.testResults;
    }

    // Clear test history
    clearTestHistory() {
        this.testResults = [];
        console.log('🧹 Test history cleared');
    }

    // Test video compatibility
    async testVideoCompatibility(videoIds) {
        console.log('🔍 Testing video compatibility...');
        const compatibility = [];
        
        for (const videoId of videoIds) {
            console.log(`Testing video: ${videoId}`);
            try {
                const results = await this.runQuickTest(videoId);
                const workingMethods = results.filter(r => r.success).length;
                
                compatibility.push({
                    videoId,
                    workingMethods,
                    totalMethods: results.length,
                    compatibility: (workingMethods / results.length) * 100
                });
            } catch (error) {
                compatibility.push({
                    videoId,
                    workingMethods: 0,
                    totalMethods: 4,
                    compatibility: 0,
                    error: error.message
                });
            }
        }
        
        console.log('📊 Video Compatibility Results:', compatibility);
        return compatibility;
    }

    async runQuickTest(videoId) {
        // Quick test without console output
        const methods = [
            () => this.testPageExtraction(videoId),
            () => this.testDirectAPI(videoId),
            () => this.testMultipleFormats(videoId),
            () => this.testAutoGenerated(videoId)
        ];
        
        const results = [];
        for (const method of methods) {
            try {
                await method();
                results.push({ success: true });
            } catch (error) {
                results.push({ success: false, error: error.message });
            }
        }
        
        return results;
    }
}

// Auto-initialize if in browser
if (typeof window !== 'undefined') {
    window.YouTubeSubtitleTester = YouTubeSubtitleTester;
    
    // Add to global for easy access
    window.testSubtitles = function(videoId) {
        const tester = new YouTubeSubtitleTester();
        return tester.runLiveTest(videoId);
    };
    
    window.testCompatibility = function(videoIds) {
        const tester = new YouTubeSubtitleTester();
        return tester.testVideoCompatibility(videoIds);
    };
    
    console.log('🧪 YouTube Subtitle Tester loaded!');
    console.log('💡 Usage: testSubtitles() or testSubtitles("VIDEO_ID")');
    console.log('💡 Batch test: testCompatibility(["VIDEO_ID1", "VIDEO_ID2"])');
}

// Export for use in other scripts
if (typeof module !== 'undefined' && module.exports) {
    module.exports = YouTubeSubtitleTester;
}
